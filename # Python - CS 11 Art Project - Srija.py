# Handlers
# Button Handlers
# to increase the size of the sprinkles 
def inc_sprinkles_handler():
    for sprinkle in sprinkles:
        sprinkle.width += 1
        if sprinkle.width > 5: # size limit of 5
            sprinkle.width = 5 
            
# to decrease the size of the sprinkles
def dec_sprinkles_handler():
    for sprinkle in sprinkles:
        sprinkle.width -= 1
        if sprinkle.width < 1: # minimum size of 1
            sprinkle.width = 1
            
  # to increase the size of the donuts
def inc_donuts_handler():
    for l in donuts:
        l.rad += 3
        if l.rad > 50: # size limit of 50
            l.rad = 50
            
# to decrease the size of the donuts
def dec_donuts_handler():           
    for x in donuts:
        x.rad -= 3 
        if x.rad < 30: # minimum size of 30
            x.rad = 30

# Handler to draw on canvas
def draw(canvas):
    canvas.draw_polygon([(0, 400), (800, 400), (800, 600), (0, 600)], 12, "#72491e", '#72491e') # draws the base of the wooden texture
    for line in patterned_lines: # draws the lines in the texture
        line.draw(canvas)
    for donut in donuts:         # draws the donuts
        donut.draw(canvas)
    for sprinkle in sprinkles:   # draws the sprinkles
        sprinkle.draw(canvas)
    for cloud in clouds:         # draws the clouds
        cloud.draw(canvas)
        # makes the clouds move
        cloud.center[0] += 1 # increments the cloud's x-coordinate by 1 
        if cloud.center[0] % WIDTH == 0:  # checks if the center has reached the edge 
            cloud.center[0] = 0 # resets the x-coordinate to 0 to make it reappear on the left side
            # randomized x and y to create different cloud shapes for each run
            cloud.center[1] = random.randint(50, 70)  
            cloud.center[0] = random.randint(50, 70)
    for rainbow in rainbows:     # draws the rainbows
        rainbow.draw(canvas)
    for s in sun:                # draws the sun
        s.draw(canvas)
        
# Frames            
# Creates a frame and assign callbacks to event handlers
frame = simplegui.create_frame("Circle Art", 800, 600)
frame.set_draw_handler(draw)

# sets a background color to the frame
frame.set_canvas_background("black")

# button to increase the size of the sprinkles
frame.add_button("increase sprinkles size", inc_sprinkles_handler)

# button to decrease the size of the sprinkles
frame.add_button("decrease sprinkles size", dec_sprinkles_handler)

# button to increase the size of the donuts
frame.add_button("increase donut size", inc_donuts_handler)

# button to decrease the size of the donuts
frame.add_button("decrease donut size", dec_donuts_handler)

# Start the frame animation
generate_donuts(x_offset, y_offset, random_colour())
generate_sprinkles(x_offset, y_offset)
rainbow()
lines()
generate_sun()
frame.start()